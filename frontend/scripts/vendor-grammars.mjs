// Vendor the TextMate grammars rook ships, from tm-grammars (a devDependency,
// never a runtime one — 11.8 MB of grammars for the ~dozen we want).
//
// The grammars are CHECKED IN on purpose, the same posture as the plugin
// catalog: a curated, pinned, auditable set rather than a package that can
// grow a new language under us. Refresh with `pnpm run grammars`, which also
// rewrites GRAMMARS.md — the provenance table (upstream repo, commit sha,
// license) that makes the vendoring reviewable.
//
// Adding a language: append to LANGUAGES, run the script, commit the diff.

import * as fs from "node:fs";
import * as path from "node:path";
import {fileURLToPath} from "node:url";
import {grammars} from "tm-grammars";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "..", "src", "highlight", "grammars");
const srcDir = path.join(here, "..", "node_modules", "tm-grammars", "grammars");

// tm-grammars name → the Monaco language id rook registers it under. Monaco's
// basic-languages already own most of these ids (their Monarch tokenizer stays
// as the fallback); svelte has no Monaco language at all, so the bridge
// registers it and .svelte files go from PLAIN TEXT to fully highlighted.
const LANGUAGES = [
    ["go", "go"],
    ["typescript", "typescript"],
    ["javascript", "javascript"],
    ["json", "json"],
    ["html", "html"],
    ["css", "css"],
    ["markdown", "markdown"],
    ["shellscript", "shell"],
    ["yaml", "yaml"],
    ["rust", "rust"],
    ["python", "python"],
    ["svelte", "svelte"],
];

fs.rmSync(outDir, {recursive: true, force: true});
fs.mkdirSync(outDir, {recursive: true});

const rows = [];
for (const [name, langId] of LANGUAGES) {
    const meta = grammars.find((g) => g.name === name);
    if (!meta) throw new Error(`tm-grammars has no grammar named ${name}`);
    const from = path.join(srcDir, `${name}.json`);
    fs.copyFileSync(from, path.join(outDir, `${name}.json`));
    rows.push({
        name,
        langId,
        scopeName: meta.scopeName,
        license: meta.license ?? "see source",
        source: meta.source ?? "",
        sha: (meta.sha ?? "").slice(0, 12),
        bytes: fs.statSync(from).size,
    });
}

const pkg = JSON.parse(
    fs.readFileSync(path.join(here, "..", "node_modules", "tm-grammars", "package.json"), "utf8"),
);
const kb = (n) => `${Math.round(n / 1024)} KB`;
const doc = `<!-- GENERATED by scripts/vendor-grammars.mjs — do not edit by hand.
     Refresh with \`pnpm run grammars\`. -->

# Vendored TextMate grammars

The syntax grammars rook ships, copied from [tm-grammars](https://github.com/shikijs/textmate-grammars-themes)
v${pkg.version} (itself a mirror of the upstream sources below).

They are checked in rather than pulled at build time so the set is pinned,
auditable, and can't grow a language without a reviewed diff — the same
posture as the plugin catalog. \`vscode-textmate\` interprets them at runtime;
Monaco's own Monarch tokenizers stay registered as the fallback for anything
not listed here.

Note on licenses: all are MIT except \`yaml\`, which comes from the TextMate
bundle collection and carries that project's permissive bundle license — the
source link is the authority, which is why the sha is recorded.

| grammar | monaco id | scope | license | size | upstream |
| --- | --- | --- | --- | --- | --- |
${rows
    .map(
        (r) =>
            `| ${r.name} | \`${r.langId}\` | \`${r.scopeName}\` | ${r.license} | ${kb(r.bytes)} | [${r.sha}](${r.source}) |`,
    )
    .join("\n")}

Total: ${kb(rows.reduce((a, r) => a + r.bytes, 0))} across ${rows.length} grammars.
`;
fs.writeFileSync(path.join(here, "..", "src", "highlight", "GRAMMARS.md"), doc);

// The registry's language table, generated alongside so it can never drift
// from what was actually copied.
const table = `// GENERATED by scripts/vendor-grammars.mjs — do not edit by hand.
// The vendored grammar set: Monaco language id, TextMate scope, and the
// loader for the grammar JSON (vite splits each into its own lazy chunk, so
// opening a Go file never downloads the TypeScript grammar).

export interface GrammarEntry {
    /** the Monaco language id this grammar tokenizes */
    lang: string;
    /** the TextMate scope name, e.g. "source.go" */
    scope: string;
    /** file extensions, for languages Monaco doesn't already register */
    extensions?: string[];
    load: () => Promise<unknown>;
}

export const GRAMMARS: GrammarEntry[] = [
${rows
    .map(
        (r) =>
            `    {\n        lang: "${r.langId}",\n        scope: "${r.scopeName}",\n        load: () => import("./grammars/${r.name}.json"),\n    },`,
    )
    .join("\n")}
];
`;
fs.writeFileSync(path.join(outDir, "..", "table.ts"), table);

console.log(`vendored ${rows.length} grammars → src/highlight/grammars/`);
