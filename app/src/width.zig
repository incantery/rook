/// 2 for East Asian Wide and Fullwidth, regional indicators and most
/// emoji; 1 for everything else.
pub fn cellWidth(cp: u21) u2 {
    if (cp < 0x1100) return 1; // nothing below here is wide
    var a: usize = 0;
    var b: usize = lo.len;
    while (a < b) {
        const mid = a + (b - a) / 2;
        if (cp > hi[mid]) {
            a = mid + 1;
        } else if (cp < lo[mid]) {
            b = mid;
        } else return 2;
    }
    return 1;
}

pub fn isWide(cp: u21) bool {
    return cellWidth(cp) == 2;
}
