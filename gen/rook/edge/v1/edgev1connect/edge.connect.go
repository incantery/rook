// The Cloud–IDE edge protocol (NEXT.md §11): the ONLY channel through
// which the Cloud requests local action and the IDE reports local truth.
//
// Design stances this file encodes, per ADR 0003:
//
//   - Reliable unary methods over ConnectRPC/HTTP. A stream, when one
//     appears, is a wake-up accelerator — delivery semantics never
//     depend on a connection staying up. The IDE polls SyncEdge.
//   - Delivery is at-least-once and repeatable. There is no "delivered"
//     state anywhere in this contract: a command is pending until a
//     device receipt resolves it, and the same command may arrive any
//     number of times.
//   - Every payload is TYPED. There is deliberately no ExecuteShell or
//     RunPrompt message, and one must never be added: a generic string
//     executor would erase the entire policy boundary this protocol
//     exists to hold (§11.2).
//   - Commands and events carry digest and signature fields. The
//     digests are filled today; signatures land with device identity
//     keys (backlog item 20) — the wire shape is ready so signing is a
//     rollout, not a migration.

